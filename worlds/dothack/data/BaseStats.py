class CharBaseStats:
    def __init__(self, base: CharData, level_up: LevelUpParam):
        self.base: CharData = base
        self.level_up: LevelUpParam = level_up

    def get_stats_at_level(self, level: int):

        level_diff: int = level - self.base.level
        result = asdict(self.base)

        result["max_hp"] = min(max(self.base.max_hp + self.level_up.max_hp * level_diff, 0), 10000)
        result["max_sp"] = min(max(self.base.max_sp + self.level_up.max_sp * level_diff, 0), 1000)
        result["attack"] = min(max(self.base.attack + self.level_up.attack * level_diff, 0), 1000)
        result["defense"] = min(max(self.base.defense + self.level_up.defense * level_diff, 0), 1000)
        result["accuracy"] = min(max(self.base.accuracy + self.level_up.accuracy * level_diff, 0), 1000)
        result["evasion"] = min(max(self.base.evasion + self.level_up.evasion * level_diff, 0), 1000)
        result["magic_attack"] = min(max(self.base.magic_attack + self.level_up.magic_attack * level_diff, 0), 1000)
        result["magic_defense"] = min(max(self.base.magic_defense + self.level_up.magic_defense * level_diff, 0), 1000)
        result["magic_accuracy"] = min(max(self.base.magic_accuracy + self.level_up.magic_accuracy * level_diff, 0), 1000)
        result["magic_evasion"] = min(max(self.base.magic_evasion + self.level_up.magic_evasion * level_diff, 0), 1000)
        result["earth"] = min(max(self.base.earth + self.level_up.earth * level_diff, 0), 1000)
        result["water"] = min(max(self.base.water + self.level_up.water * level_diff, 0), 1000)
        result["fire"] = min(max(self.base.fire + self.level_up.fire * level_diff, 0), 1000)
        result["wood"] = min(max(self.base.wood + self.level_up.wood * level_diff, 0), 1000)
        result["light"] = min(max(self.base.light + self.level_up.light * level_diff, 0), 1000)
        result["dark"] = min(max(self.base.dark + self.level_up.dark * level_diff, 0), 1000)
        result["soul"] = min(max(self.base.soul + self.level_up.soul * level_diff, 0), 1000)
        result["body"] = min(max(self.base.body + self.level_up.body * level_diff, 0), 1000)

        return CharData(**result)


